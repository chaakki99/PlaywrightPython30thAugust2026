#Case 8: How to Remove elements in the List using pop method
# Declare a List
cities = ["Mysore","Hassan",45,100,True,10.75,False,"Sira","Mysore","Hassan"]
print(cities)
# Remove Elements
cities.pop()
print(cities)
cities.pop()
print(cities)
# Remove Elements based on index
cities.pop(0)
print(cities)
cities.pop(2)
print(cities)